import { useState } from 'react';
import html2canvas from 'html2canvas';
import jsPDF from 'jspdf';
import { toast } from 'sonner';
import { MarkdownRenderer } from './MarkdownRenderer';

/**
 * Exports chat content as a high-fidelity PDF with compiled LaTeX math.
 * Uses html2canvas to capture the rendered output exactly as shown.
 */
export async function exportRenderedPDF(
  content: string,
  title: string = 'TanoAI_Response'
): Promise<void> {
  const container = document.createElement('div');
  container.style.cssText = `
    position: fixed;
    left: -9999px;
    top: 0;
    width: 794px;
    max-width: 794px;
    padding: 48px;
    background: white;
    color: black;
    font-family: 'Inter', 'Segoe UI', Roboto, sans-serif;
    font-size: 15px;
    line-height: 1.7;
    z-index: -1;
  `;
  
  document.body.appendChild(container);

  try {
    const { createRoot } = await import('react-dom/client');
    const root = createRoot(container);
    
    await new Promise<void>((resolve) => {
      root.render(
        <div className="pdf-export-container">
          <div style={{ marginBottom: '28px', paddingBottom: '18px', borderBottom: '2px solid #e5e7eb' }}>
            <h1 style={{ fontSize: '26px', fontWeight: 'bold', color: '#111827', margin: 0 }}>
              {title}
            </h1>
            <p style={{ fontSize: '12px', color: '#6b7280', marginTop: '10px' }}>
              Generated by TanoAI • {new Date().toLocaleDateString('en-US', { 
                year: 'numeric', month: 'long', day: 'numeric' 
              })}
            </p>
          </div>
          
          <div style={{ color: '#374151' }}>
            <MarkdownRenderer content={content} className="pdf-render-mode" />
          </div>
        </div>
      );
      
      // Wait for KaTeX rendering to complete
      setTimeout(resolve, 2000);
    });

    const canvas = await html2canvas(container, {
      scale: 3,
      useCORS: true,
      logging: false,
      backgroundColor: '#ffffff',
      width: container.scrollWidth,
      height: container.scrollHeight,
      windowWidth: container.scrollWidth,
      windowHeight: container.scrollHeight,
    });

    const pdf = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
    });

    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = pdf.internal.pageSize.getHeight();
    
    const imgWidth = pdfWidth;
    const imgHeight = (canvas.height * pdfWidth) / canvas.width;
    
    const imgData = canvas.toDataURL('image/png', 1.0);
    
    let heightLeft = imgHeight;
    let position = 0;
    
    pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight, undefined, 'FAST');
    heightLeft -= pdfHeight;
    
    while (heightLeft > 0) {
      position = heightLeft - imgHeight;
      pdf.addPage();
      pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight, undefined, 'FAST');
      heightLeft -= pdfHeight;
    }

    const totalPages = pdf.getNumberOfPages();
    for (let i = 1; i <= totalPages; i++) {
      pdf.setPage(i);
      pdf.setFontSize(10);
      pdf.setTextColor(128);
      pdf.text(
        `Page ${i} of ${totalPages} • TanoAI`,
        pdfWidth / 2,
        pdfHeight - 10,
        { align: 'center' }
      );
    }

    root.unmount();
    
    const sanitizedTitle = title.replace(/[^a-zA-Z0-9\s]/g, '').replace(/\s+/g, '_');
    pdf.save(`${sanitizedTitle}.pdf`);
    
    toast.success('PDF exported with compiled math!');
  } catch (error) {
    console.error('Rendered PDF export failed:', error);
    toast.error('Failed to export PDF');
    throw error;
  } finally {
    if (container.parentNode) {
      container.parentNode.removeChild(container);
    }
  }
}

// Inject PDF export styles
if (typeof document !== 'undefined') {
  const styleId = 'pdf-export-styles';
  if (!document.getElementById(styleId)) {
    const style = document.createElement('style');
    style.id = styleId;
    style.textContent = `
.pdf-render-mode .katex { font-size: 1.1em !important; }
.pdf-render-mode .katex-display { margin: 16px 0 !important; overflow: visible !important; }
.pdf-render-mode pre { background: #f3f4f6 !important; border: 1px solid #e5e7eb !important; border-radius: 8px !important; padding: 16px !important; }
.pdf-render-mode code { background: #f3f4f6 !important; color: #374151 !important; }
.pdf-render-mode h1, .pdf-render-mode h2, .pdf-render-mode h3 { color: #111827 !important; }
.pdf-render-mode ul, .pdf-render-mode ol { padding-left: 24px !important; }
.pdf-render-mode blockquote { border-left: 4px solid #6366f1 !important; background: #f5f3ff !important; padding: 12px 16px !important; }
.pdf-render-mode table { border-collapse: collapse !important; width: 100% !important; }
.pdf-render-mode th, .pdf-render-mode td { border: 1px solid #e5e7eb !important; padding: 8px 12px !important; }
.pdf-render-mode th { background: #f9fafb !important; }
`;
    document.head.appendChild(style);
  }
}
