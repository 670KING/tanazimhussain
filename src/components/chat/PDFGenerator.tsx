import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { 
  Dialog, 
  DialogContent, 
  DialogDescription, 
  DialogHeader, 
  DialogTitle, 
  DialogTrigger 
} from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Textarea } from '@/components/ui/textarea';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { FileText, Download, Loader2, Sparkles } from 'lucide-react';
import { toast } from 'sonner';
import jsPDF from 'jspdf';

interface PDFGeneratorProps {
  onGenerateWithAI: (prompt: string, options: PDFOptions) => Promise<string>;
  isLoading?: boolean;
}

export interface PDFOptions {
  title: string;
  type: 'assignment' | 'report' | 'notes' | 'essay' | 'research' | 'cheatsheet';
  style: 'academic' | 'professional' | 'casual';
  length: 'short' | 'medium' | 'long';
}

export function PDFGenerator({ onGenerateWithAI, isLoading }: PDFGeneratorProps) {
  const [open, setOpen] = useState(false);
  const [prompt, setPrompt] = useState('');
  const [options, setOptions] = useState<PDFOptions>({
    title: '',
    type: 'assignment',
    style: 'academic',
    length: 'medium',
  });
  const [generatedContent, setGeneratedContent] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);

  const handleGenerate = async () => {
    if (!prompt.trim()) {
      toast.error('Please enter a topic or prompt');
      return;
    }

    setIsGenerating(true);
    try {
      const content = await onGenerateWithAI(prompt, options);
      setGeneratedContent(content);
      toast.success('Content generated! You can now download the PDF.');
    } catch (error) {
      toast.error('Failed to generate content');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleDownloadPDF = () => {
    if (!generatedContent) {
      toast.error('Generate content first');
      return;
    }

    try {
      const doc = new jsPDF();
      const pageWidth = doc.internal.pageSize.getWidth();
      const pageHeight = doc.internal.pageSize.getHeight();
      const margin = 20;
      const maxWidth = pageWidth - margin * 2;
      
      // Title
      doc.setFontSize(24);
      doc.setFont('helvetica', 'bold');
      const title = options.title || 'Generated Document';
      doc.text(title, margin, 30);

      // Subtitle
      doc.setFontSize(12);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(128);
      doc.text(`Generated by TanoAI • ${new Date().toLocaleDateString()}`, margin, 40);
      doc.setTextColor(0);

      // Separator line
      doc.setDrawColor(200);
      doc.line(margin, 45, pageWidth - margin, 45);

      // Content
      doc.setFontSize(11);
      doc.setFont('helvetica', 'normal');
      
      const lines = doc.splitTextToSize(generatedContent, maxWidth);
      let y = 55;
      
      for (const line of lines) {
        if (y > pageHeight - margin) {
          doc.addPage();
          y = margin;
        }
        
        // Handle headers (lines starting with # or all caps)
        if (line.startsWith('#') || (line === line.toUpperCase() && line.length > 3)) {
          doc.setFont('helvetica', 'bold');
          doc.text(line.replace(/^#+\s*/, ''), margin, y);
          doc.setFont('helvetica', 'normal');
        } else {
          doc.text(line, margin, y);
        }
        
        y += 7;
      }

      // Footer
      const pageCount = doc.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(10);
        doc.setTextColor(128);
        doc.text(
          `Page ${i} of ${pageCount} • TanoAI`,
          pageWidth / 2,
          pageHeight - 10,
          { align: 'center' }
        );
      }

      doc.save(`${title.replace(/\s+/g, '_')}.pdf`);
      toast.success('PDF downloaded successfully!');
    } catch (error) {
      console.error('PDF generation error:', error);
      toast.error('Failed to generate PDF');
    }
  };

  const resetForm = () => {
    setPrompt('');
    setGeneratedContent('');
    setOptions({
      title: '',
      type: 'assignment',
      style: 'academic',
      length: 'medium',
    });
  };

  return (
    <Dialog open={open} onOpenChange={(isOpen) => {
      setOpen(isOpen);
      if (!isOpen) resetForm();
    }}>
      <DialogTrigger asChild>
        <Button variant="outline" size="sm" className="gap-2">
          <FileText className="w-4 h-4" />
          Generate PDF
        </Button>
      </DialogTrigger>
      <DialogContent className="max-w-2xl max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-primary" />
            AI PDF Generator
          </DialogTitle>
          <DialogDescription>
            Generate professional PDFs for assignments, reports, essays, and more using AI.
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-4 py-4">
          {/* Title */}
          <div className="space-y-2">
            <Label>Document Title</Label>
            <Input
              placeholder="e.g., Research Paper on Climate Change"
              value={options.title}
              onChange={(e) => setOptions({ ...options, title: e.target.value })}
            />
          </div>

          {/* Type & Style */}
          <div className="grid grid-cols-2 gap-4">
            <div className="space-y-2">
              <Label>Document Type</Label>
              <Select 
                value={options.type} 
                onValueChange={(v) => setOptions({ ...options, type: v as PDFOptions['type'] })}
              >
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="assignment">Assignment</SelectItem>
                  <SelectItem value="report">Report</SelectItem>
                  <SelectItem value="notes">Study Notes</SelectItem>
                  <SelectItem value="essay">Essay</SelectItem>
                  <SelectItem value="research">Research Paper</SelectItem>
                </SelectContent>
              </Select>
            </div>

            <div className="space-y-2">
              <Label>Writing Style</Label>
              <Select 
                value={options.style} 
                onValueChange={(v) => setOptions({ ...options, style: v as PDFOptions['style'] })}
              >
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="academic">Academic</SelectItem>
                  <SelectItem value="professional">Professional</SelectItem>
                  <SelectItem value="casual">Casual</SelectItem>
                </SelectContent>
              </Select>
            </div>
          </div>

          {/* Length */}
          <div className="space-y-2">
            <Label>Length</Label>
            <Select 
              value={options.length} 
              onValueChange={(v) => setOptions({ ...options, length: v as PDFOptions['length'] })}
            >
              <SelectTrigger>
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="short">Short (1-2 pages)</SelectItem>
                <SelectItem value="medium">Medium (3-5 pages)</SelectItem>
                <SelectItem value="long">Long (6+ pages)</SelectItem>
              </SelectContent>
            </Select>
          </div>

          {/* Prompt */}
          <div className="space-y-2">
            <Label>Topic / Instructions</Label>
            <Textarea
              placeholder="Describe what you want in the document. Be specific about topics, requirements, and any particular points to cover..."
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              rows={4}
            />
          </div>

          {/* Generated content preview */}
          {generatedContent && (
            <div className="space-y-2">
              <Label>Generated Content Preview</Label>
              <div className="bg-muted/50 rounded-lg p-4 max-h-48 overflow-y-auto text-sm whitespace-pre-wrap">
                {generatedContent.slice(0, 1000)}
                {generatedContent.length > 1000 && '...'}
              </div>
            </div>
          )}

          {/* Actions */}
          <div className="flex justify-end gap-2 pt-4">
            {generatedContent ? (
              <>
                <Button variant="outline" onClick={resetForm}>
                  Start Over
                </Button>
                <Button onClick={handleDownloadPDF} className="gap-2">
                  <Download className="w-4 h-4" />
                  Download PDF
                </Button>
              </>
            ) : (
              <Button 
                onClick={handleGenerate} 
                disabled={isGenerating || !prompt.trim()}
                className="gap-2"
              >
                {isGenerating ? (
                  <>
                    <Loader2 className="w-4 h-4 animate-spin" />
                    Generating...
                  </>
                ) : (
                  <>
                    <Sparkles className="w-4 h-4" />
                    Generate Content
                  </>
                )}
              </Button>
            )}
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}

// Quick PDF from content
export function downloadTextAsPDF(content: string, title: string = 'Document') {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const maxWidth = pageWidth - margin * 2;
  
  // Title
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(title, margin, 25);

  // Date
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(128);
  doc.text(`Generated on ${new Date().toLocaleDateString()}`, margin, 33);
  doc.setTextColor(0);

  // Line
  doc.setDrawColor(200);
  doc.line(margin, 38, pageWidth - margin, 38);

  // Content
  doc.setFontSize(11);
  const lines = doc.splitTextToSize(content, maxWidth);
  let y = 48;
  
  for (const line of lines) {
    if (y > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
    doc.text(line, margin, y);
    y += 6;
  }

  doc.save(`${title.replace(/\s+/g, '_')}.pdf`);
}
